"""Copy Study I's registered results into the page's data file (no number is typed by hand).

    python scripts/import_results.py /path/to/FWI

Reads the thesis repository's result files and writes assets/data/study1-results.json and
assets/data/study1-results.js (the same object as window.AE_RESULTS, so the page also works
from file://). Sources, all under results/study-1-cross-field-attribution/:
- 2026-10-06-confirmatory-analysis/{outcome.json, point_shares.csv, regime.csv}   H1 test
- 2026-10-12-prior-dependence-loss/prior_dependence.csv  prior-level deficit (dependent priors)
- 2026-10-12-f1-reading/{verdicts.csv, deficit_by_checkpoint.csv}      follow-up F1
- 2026-09-14-attribution-snr-stride-v2/metrics/attribution_grid.csv    exact-grid summary counts
"""
import csv
import json
import sys
from pathlib import Path

FWI = Path(sys.argv[1])
RES = FWI / "results/study-1-cross-field-attribution"
OUT = Path(__file__).resolve().parents[1] / "assets/data"


def rows(path: Path) -> list[dict]:
    with path.open() as handle:
        return list(csv.DictReader(handle))


def main() -> None:
    conf = RES / "2026-10-06-confirmatory-analysis"
    outcome = json.loads((conf / "outcome.json").read_text())
    points = []
    for r in rows(conf / "point_shares.csv"):
        run = r["run"]
        points.append({"kappa": float(run.split("kappa")[1].split("-")[0]),
                       "informative": "informative" in run, "s": float(r["s"]), "seeds": int(r["n_seeds"]),
                       "pred_O": float(r["pred_O"]), "pred_P": float(r["pred_P"]),
                       "meas_O": float(r["meas_O"]), "meas_P": float(r["meas_P"]),
                       "magnitude_error": float(r["magnitude_error"])})
    prior_loss = [{"s": float(r["shared_fraction"]), "seed": int(r["train_seed"]), "P": int(r["P"]),
                   "deficit": float(r["relative_deficit"])}
                  for r in rows(RES / "2026-10-12-prior-dependence-loss/prior_dependence.csv") if r["P"] == "1"]
    f1 = RES / "2026-10-12-f1-reading"
    curves = [{"s": float(r["shared_fraction"]), "N": int(r["train_size"]), "steps": int(r["steps"]),
               "mean": float(r["mean"]), "min": float(r["min"]), "max": float(r["max"])}
              for r in rows(f1 / "deficit_by_checkpoint.csv")]
    verdicts = [{"s": float(r["shared_fraction"]), "N": int(r["train_size"]), "verdict": r["verdict"],
                 "seeds_up": int(r["seeds_160k_above_20k"]), "seeds": int(r["n_seeds"])}
                for r in rows(f1 / "verdicts.csv")]
    grid = rows(RES / "2026-09-14-attribution-snr-stride-v2/metrics/attribution_grid.csv")
    signed = [r for r in grid if r["functional"] == "mean_signed_pointwise_correlation"]
    coupled = [r for r in signed if float(r["shared_fraction"]) > 0 and float(r["kappa"]) > 0]
    mi = [r for r in grid if r["functional"] == "mutual_information" and float(r["shared_fraction"]) > 0]
    negative = [float(r["total"]) for r in coupled if float(r["total"]) < 0]
    grid_summary = {"coupled_cells": len(coupled), "coupled_cells_negative_total": len(negative),
                    "negative_total_min": min(negative), "negative_total_max": max(negative),
                    "coupled_cells_opposing": sum(r["shares_oppose"] == "True" for r in coupled),
                    "mi_cells_with_s": len(mi), "mi_negative_prior_share": sum(float(r["phi_P"]) < 0 for r in mi)}
    regime = rows(conf / "regime.csv")
    regime_summary = {"priors": len(regime), "inside": sum(r["inside"] == "True" for r in regime)}
    data = {"confirmatory": {"outcome": outcome, "points": points, "regime": regime_summary}, "prior_loss": prior_loss,
            "f1": {"curves": curves, "verdicts": verdicts}, "exact_grid": grid_summary}
    OUT.mkdir(parents=True, exist_ok=True)
    text = json.dumps(data, indent=1)
    (OUT / "study1-results.json").write_text(text + "\n")
    (OUT / "study1-results.js").write_text("// Generated by scripts/import_results.py; do not edit.\n"
                                           "window.AE_RESULTS = " + text + ";\n")
    print(json.dumps(grid_summary))


if __name__ == "__main__":
    main()
